      T(3,5) = - H*(NB*VSCSM + 2.0*NMB*VSSCM)
      T(3,7) = - (WMN*H0*VSSCM + 2.0*NMB*H*VSCSM - H0*SY)
      T(3,8) = H0*VSCCM - 2.0*NMB*H*VSSSM
      T(3,18) = H*H0*(NB*VSCY - RH*NB*VSSSM
     1 - 2.0*NMB*VSDCM)
      T(3,19) = RH*(NB*VSSY + VSSCM - 2.0*NMB*VSDSM)
