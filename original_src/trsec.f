      T(5,1) = - (TNTM*(L - SX*CX)
     1 + 4.0*NMB*(L - SX))*H0**2/(12.0*WMN)
      T(5,2) = - 2.0*NMB*(1.0 - CX)/(3.0*WMN**2)
     1 + TNTM*H0**2*SX**2/(6.0*WMN)
      T(5,3) = - (2.0*(FMTB + 2.0*NMB)*(L - SX)
