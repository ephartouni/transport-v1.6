      FMTB = 5.0*NB - 2.0*BEB - 3.0
      NNM2 = NB*(NB + 1.0) - 2.0*BEB
      TNSM = 3.0*NB**2 - 2.0*NB - 4.0*BEB + 3.0
      TNTM = NB*(3.0*NB - 1.0) - 2.0*BEB
