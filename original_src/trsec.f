      T(1,1) = H0**2*(TNMB*H*HSCX2
     1 + 0.5*WMN**2*(H0 - HEX)*HSSX2)
      T(1,2) = H0*(H0*(2.0*H*TNMB - WMN*(H0 - HEX))*HSCSX
     1 + SX)
      T(1,3) = TNMB*H*HSSX2
     1 + 0.5*(H0 - HEX)*HSCX2
      T(1,6) = - 0.5*H0**2*H*(NMTB*HSCY2
     1 + NB**2*RH**2*HSSY2)
      T(1,9) = H*(- NMTB + NB*RH)*HSCSY
