      VPCSM = 0.5*(1.0 + WMN/WM5N)*SX*SY
     1 - WMN*CY*DISN/WM5N
      VPSCM = 0.5*(1.0 + WMN/WM5N)*CY*DISN
     1 - RH*NB*SX*SY/WM5N
