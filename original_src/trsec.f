     1 + (H0 - HEX)*HPCSX - H0*CX*DISN - H0*SX**2)
      T(2,21) = H*(TNMB*HPDX2 + TMN*HPDX
     1 - SX + 0.5*H*(H0 - HEX)*HPSX2 - H0*H*SX*DISN)
