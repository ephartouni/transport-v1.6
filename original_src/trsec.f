      ELSE
        VPSSM = 0.5*SY*((1.0 - CX)/WMN - (1.0 + CX)/WM5N)
     1   + SX*CY/WM5N
        VPDCM = RH*(RH*NB*SY*(1.0 + CX)/(WMN*WM5N)
     1   + 0.5*(SY + L*CY)/WMN
     2   - 0.5*(1.0/WMN + 1.0/WM5N)*SX*CY)
        VPDSM = RH*(CY*DISN/WM5N + 0.5*SY*L/WMN
     1   - 0.5*(1.0/WMN + 1.0/WM5N)*SX*SY)
      ENDIF
