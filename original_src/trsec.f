     1   + 0.5*SY*(1.0 + CX)/WM5N - SX*CY/WM5N
        VSSSM = (2.0*CY*DISN - SX*SY)/WM5N
        VSDCM =  RH*( - CY*DISN/WM5N + 0.5*L*SY/WMN
     1   + 0.5*(1.0/WM5N - 1.0/WMN)*SX*SY)
        VSDSM = (RH*SY*(1.0 + CX)/WM5N
